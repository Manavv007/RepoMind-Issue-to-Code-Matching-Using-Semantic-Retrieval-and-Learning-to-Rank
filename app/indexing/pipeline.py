"""Indexing pipeline: load -> walk -> parse -> extract -> store.

This module never imports or executes repository code; files are read as bytes
and parsed with Tree-sitter.
"""

from __future__ import annotations

import hashlib
import logging
import re
import time
from collections import Counter
from collections.abc import Sequence
from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path

from app.config import Settings, get_settings
from app.ingestion.errors import (
    IndexingTimeoutError,
    NoSupportedFilesError,
    UnsupportedLanguageError,
)
from app.ingestion.file_walker import walk_repository
from app.ingestion.repository_loader import LoadedRepository, RepositoryLoader
from app.parsing.symbol_extractor import extract_file
from app.parsing.tree_sitter_parser import SUPPORTED_LANGUAGES
from app.schemas.code_unit import CodeUnit, FileRecord, RepositoryRecord
from app.storage.index_store import IndexStore, sqlite_path_from_url

logger = logging.getLogger(__name__)

_GENERATED_RE = re.compile(
    rb"^\s*#.*(auto-?generated|generated by|do not edit|@generated)", re.IGNORECASE
)


@dataclass
class IndexResult:
    """Summary of an indexing run."""

    repository: RepositoryRecord
    checkout_path: Path
    units_by_kind: dict[str, int]
    skipped: dict[str, int]
    files_with_syntax_errors: int
    elapsed_seconds: float
    warnings: list[str] = field(default_factory=list)


def make_repo_id(source: str, commit: str, content_hash: str | None = None) -> str:
    """Deterministic repository id from source, commit (and content if dirty)."""
    seed = f"{source}@{commit}" + (f"+{content_hash}" if content_hash else "")
    return hashlib.sha1(seed.encode("utf-8")).hexdigest()[:16]  # noqa: S324 - id only


def _is_generated(data: bytes) -> bool:
    head_lines = data.split(b"\n", 5)[:5]
    return any(_GENERATED_RE.match(line) for line in head_lines)


def index_repository(
    source: str,
    *,
    commit: str | None = None,
    languages: Sequence[str] = ("python",),
    settings: Settings | None = None,
    store: IndexStore | None = None,
    loader: RepositoryLoader | None = None,
    include_nested_functions: bool = False,
) -> IndexResult:
    """Index a repository revision into the SQLite store.

    Args:
        source: Public GitHub URL or local directory path.
        commit: Optional commit hash to pin (7-40 hex chars).
        languages: Languages to index (Phase 1 supports ``python`` only).

    Raises:
        IngestionError: (or a subclass) with a stable ``code`` on failure.
    """
    started = time.monotonic()
    settings = settings or get_settings()

    unsupported = [lang for lang in languages if lang not in SUPPORTED_LANGUAGES]
    if unsupported:
        raise UnsupportedLanguageError(
            f"Unsupported language(s): {', '.join(unsupported)}. "
            f"Supported: {', '.join(sorted(SUPPORTED_LANGUAGES))}."
        )

    loader = loader or RepositoryLoader(settings)
    store = store or IndexStore(sqlite_path_from_url(settings.database_url))

    loaded = loader.load(source, commit)
    warnings = list(loaded.warnings)

    walk = walk_repository(
        loaded.root,
        languages=frozenset(languages),
        max_file_size_bytes=settings.max_file_size_kb * 1024,
        max_total_bytes=settings.max_repo_size_mb * 1024 * 1024,
        max_files=settings.max_files,
    )
    skipped: Counter[str] = Counter(walk.skipped)
    if not walk.files:
        raise NoSupportedFilesError(
            f"No indexable {'/'.join(languages)} files were found in the repository."
        )

    deadline = started + settings.max_index_seconds
    file_records: list[FileRecord] = []
    units: list[CodeUnit] = []
    for sf in walk.files:
        if time.monotonic() > deadline:
            raise IndexingTimeoutError(
                f"Indexing exceeded the {settings.max_index_seconds}s limit."
            )
        try:
            raw = sf.abs_path.read_bytes()
        except OSError:
            skipped["unreadable"] += 1
            continue
        if b"\x00" in raw[:8192]:
            skipped["binary"] += 1
            continue
        if _is_generated(raw):
            skipped["generated"] += 1
            continue
        try:
            extracted = extract_file(
                sf.rel_path,
                sf.language,
                raw,
                include_nested_functions=include_nested_functions,
            )
        except (RecursionError, ValueError) as exc:
            logger.warning("Failed to parse %s: %s", sf.rel_path, exc)
            skipped["parse_failed"] += 1
            continue
        file_records.append(extracted.record)
        units.extend(extracted.units)

    if not file_records:
        raise NoSupportedFilesError("No source files could be parsed.")

    content_hash = hashlib.sha256(
        "\n".join(f"{f.path}:{f.sha256}" for f in file_records).encode("utf-8")
    ).hexdigest()[:12]
    if loaded.commit is None:
        commit_id = f"local:{content_hash}"
        repo_id = make_repo_id(loaded.source, commit_id)
    else:
        commit_id = loaded.commit
        repo_id = make_repo_id(
            loaded.source, commit_id, content_hash if loaded.dirty else None
        )

    syntax_error_files = sum(1 for f in file_records if f.has_syntax_errors)
    if syntax_error_files:
        warnings.append(
            f"{syntax_error_files} file(s) contain syntax errors; "
            "extracted symbols from them may be incomplete."
        )

    record = RepositoryRecord(
        repo_id=repo_id,
        source=loaded.source,
        source_type=loaded.source_type,
        commit=commit_id,
        dirty=loaded.dirty,
        languages=tuple(sorted({f.language for f in file_records})),
        num_files=len(file_records),
        num_units=len(units),
        indexed_at=datetime.now(UTC).isoformat(timespec="seconds"),
    )
    store.replace_repository(record, file_records, units)

    return IndexResult(
        repository=record,
        checkout_path=loaded.root,
        units_by_kind=dict(Counter(u.kind for u in units)),
        skipped=dict(skipped),
        files_with_syntax_errors=syntax_error_files,
        elapsed_seconds=round(time.monotonic() - started, 3),
        warnings=warnings,
    )


__all__ = ["IndexResult", "LoadedRepository", "index_repository", "make_repo_id"]
